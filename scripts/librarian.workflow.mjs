// parallelFanout BATCHES at maxInFlight and every batch is a BARRIER: batch 2 cannot start until
// every unit in batch 1 is terminal. A hardcoded 8 does not remove that cliff, it relocates it to
// the 9th sub-question. Default 8 preserves today's behavior when `cap` is absent.
// 16 is the Workflow runtime's own hard ceiling on concurrent agents (min(16, cores − 2)), so a
// larger cap cannot buy parallelism — it only puts every unit in one batch and lets the runtime
// queue them while their watchdogs already tick, which is the failure the note above describes.
// Floor because a fractional cap reaches parallelFanout's chunk() as a fractional slice size.
const MAX_CONCURRENT = (cap && cap > 0) ? Math.min(Math.floor(cap), 16) : 8;
// maxSearchesPerLeaf: appends a "search at most N times then synthesize" instruction to the
// research-leaf prompt. DEFAULTED, not optional.
//
// Measured on run wf_cd105af0-fab with the value unset, via scripts/measure-workflow-run.mjs:
// 15 research leaves ran 214 turns and 448 tool calls between them — ~14 turns and ~30 tool calls
// EACH — re-reading 9.84M tokens of context to produce 85K of output. That is a 116:1 read-to-write
// ratio and 73% of the entire run's cache reads, from 16% of its agents.
//
// (Figures corrected 2026-08-14. Earlier comments here cited 1.52M per leaf, 250:1, 68% and ~24M
// run-wide. Those came from a transcript reader that summed each message's usage once per content
// block, inflating every token figure ~2.7x. The argument was never in doubt; the numbers were.)
//
// A caller may raise it for an unusually broad topic. Leaving it unset is what made research the
// single most expensive phase of that run.
if (!Array.isArray(subQuestions) || subQuestions.length === 0) {
  throw new TypeError('librarian: args.subQuestions must be a non-empty string[]');
}
// Research leaves are configurable (default Sonnet); the judgment steps (verify + synth) stay Sonnet.
const LEAF_MODEL = leafModel || 'claude-sonnet-4-6';
// harvestPerLeaf: the hard cap on harvest agents per sub-question, and the control that keeps this
// phase inside its budget. Measured 2026-08-15: an agent costs a ~23 K fixed floor regardless of
// prompt size, cut to ~34% of that by restricting its toolset (measured on these three types at
// Task 1). At 4 harvests a sub-question costs ~80 K against ~98 K today; at 6 it is ~100 K and the
// slice stops paying for itself. Raising this is a deliberate budget decision, not a tuning knob.
const HARVEST_PER_LEAF = (harvestPerLeaf && harvestPerLeaf > 0) ? Math.floor(harvestPerLeaf) : 4;
// Haiku for harvest ONLY. It is mechanical single-page extraction — copy spans out of one page —
// which is the one job in this pipeline that is not judgment. Synthesis stays Sonnet.
const HARVEST_MODEL = 'claude-haiku-4-5-20251001';
// roundsBudget: how many sub-questions across the WHOLE run may have a second research round.
// Per-unit capping alone is not enough — round 2 on all nine units would add ~540 K and erase the
// slice's ~160 K win. Spent neediest-first; a unit denied a round publishes on round-1 evidence
// with its gaps recorded, never silently.
const ROUNDS_BUDGET = (roundsBudget != null && roundsBudget >= 0) ? Math.floor(roundsBudget) : 3;
// Round 2 is gap-filling, not a re-run: half the width of round 1.
const ROUND2_HARVEST = 2;
// The two fan-out layers MULTIPLY. MAX_CONCURRENT was the whole in-flight budget when a unit was
// one agent; a unit is now one agent plus up to HARVEST_PER_LEAF concurrent harvests, so running
// MAX_CONCURRENT units would put MAX_CONCURRENT x HARVEST_PER_LEAF agents against a runtime ceiling
// of min(16, cores - 2). The runtime does not reject the excess — it QUEUES it, while each queued
// agent's watchdog already ticks. That is the "fan-out steps fail first" cascade the regulation
// layer exists to prevent (see docs/explanation/orchestration-regulation-layer.md).
//
// The cost of this division is more batch barriers and a longer wall clock. That is the cheaper of
// the two failures: a barrier costs time, a saturated pool costs the run.
const OUTER_IN_FLIGHT = Math.max(1, Math.floor(MAX_CONCURRENT / HARVEST_PER_LEAF));
const researchIntegrity = [];

// Research findings are CITED: every claim carries the source URL it came from + the sub-question it answers.
// Research findings are CITED: every claim carries the source URL it came from + the sub-question it answers.
// `excerpt` is the verbatim span excerptGuard checks against the harvested text. It is OPTIONAL in the
// schema and enforced by the guard, not by validation — the parent plan's Task 17 owns promoting it to
// a contractual required field, and a required field here would reject the reframe path, which still
// runs the single-agent shape and produces no excerpt.
const FINDINGS = { type: 'object', required: ['findings'], properties: { findings: { type: 'array',
  items: { type: 'object', required: ['subQuestion', 'claim', 'source'], properties: {
    subQuestion: { type: 'string' }, claim: { type: 'string' }, source: { type: 'string' },
    excerpt: { type: 'string' }, detail: { type: 'string' } } } },
  gaps: { type: 'array', items: { type: 'string' } } } };

const SEARCH_RESULTS = { type: 'object', required: ['results'], properties: { results: { type: 'array',
  items: { type: 'object', required: ['url'], properties: {
    url: { type: 'string' }, title: { type: 'string' }, why: { type: 'string' } } } } } };

const QUOTE_BUNDLE = { type: 'object', required: ['url', 'spans'], properties: {
  url: { type: 'string' }, publishedDate: { type: 'string' },
  spans: { type: 'array', items: { type: 'string' } } } };

phase('Research');
// One regulated unit per sub-question — unchanged, deliberately. The fan-out is now NESTED (each
// unit runs 6 agents), and parallelFanout BATCHES at maxInFlight with a BARRIER between batches, so
// flattening 9x6 into one fan-out would serialise badly. Keeping the sub-question as the unit
// preserves the engine's watchdog, quorum and validate contract at the level they were designed for.
//
// The three stages are tool-restricted agent types, not prompt instructions. Today's single research
// agent is TOLD "do not answer from memory" and "search at most N times"; the parent plan's Task 12
// exists because that was ignored 16 times out of 16. Removing the tool removes the option.

/** Stage 1 — rank URLs. WebSearch only: structurally cannot fetch. */
const searchStage = (q, exclude) => agent(
  `Rank the most promising web sources for this sub-question. Do NOT answer it.\n` +
  `SUB-QUESTION: ${q}\n` +
  (brief ? `OVERALL RESEARCH GOAL (context only): ${brief}\n` : '') +
  `Search budget: perform at most ${maxSearchesPerLeaf} WebSearch calls.\n` +
  `Return at most ${HARVEST_PER_LEAF * 2} results, best first — a later stage caps how many are read, so rank matters more than volume.\n` +
  (exclude.length ? `ALREADY READ — do not return these: ${exclude.join(', ')}\n` : '') +
  (seedText ? `\n--- SEED CONTEXT (the user's draft; a topic map only — do NOT treat it as a source) ---\n${seedText}` : ''),
  { label: `search:${q.slice(0, 40)}`, phase: 'Research', schema: SEARCH_RESULTS,
    model: LEAF_MODEL, agentType: 'web-search' });

/** Stage 2 — one page, one agent, verbatim spans out. WebFetch only. */
const harvestStage = (q, url) => agent(
  `Fetch this ONE page and copy out the passages that bear on the sub-question.\n` +
  `URL: ${url}\n` +
  `SUB-QUESTION: ${q}\n` +
  `Copy each passage character-for-character from the page — a rewritten span invalidates every finding built on it. Return the page's publication date if it states one.\n` +
  `If the page is dead, paywalled, or off-topic, return an empty spans array. Do NOT substitute another source and do NOT answer from your own knowledge.\n`,
  { label: `harvest:${url.slice(0, 48)}`, phase: 'Research', schema: QUOTE_BUNDLE,
    model: HARVEST_MODEL, agentType: 'page-harvest' });

/** Stage 3 — quotes in, cited findings out. No web tool: cannot add an unsourced claim. */
const synthesizeStage = (q, bundles) => agent(
  `Turn these verbatim quote bundles into findings for ONE sub-question. You have no web tool — everything you may assert is below.\n` +
  `SUB-QUESTION: ${q}\n` +
  (brief ? `OVERALL RESEARCH GOAL (context only): ${brief}\n` : '') +
  `Set "subQuestion" on EVERY finding to exactly: ${q}\n` +
  `Set "source" to the bundle URL the claim came from, and "excerpt" to one of that bundle's spans (or a contiguous substring of one), copied exactly. An excerpt that is not a real substring of its source's spans is DROPPED, and one under 80 characters is dropped as unusable.\n` +
  `Name any genuinely missing facts in "gaps" — concrete gaps, not a restatement of the topic.\n` +
  `\nQUOTE BUNDLES:\n${JSON.stringify(bundles)}`,
  { label: `synth:${q.slice(0, 44)}`, phase: 'Research', schema: FINDINGS,
    model: LEAF_MODEL, agentType: 'synthesize' });

// The round is split into a cheap half and an expensive half so a caller can decide BETWEEN them.
// Round 2 uses that seam to check convergence after paying for one search but before paying for a
// harvest fan-out and a synthesis. Fused into one function, a convergence check could only ever run
// after the whole round's spend, which would make it a log-message chooser rather than a control.

/** Cheap half: one search, then the pure cap/dedupe. */
async function searchAndSelect(q, exclude, cap) {
  const search = await searchStage(q, exclude);
  const searched = (search?.results ?? []).map((r) => r?.url).filter((u) => typeof u === 'string');
  return { searched, targets: selectHarvestTargets(search?.results ?? [], cap, exclude) };
}

/**
 * Expensive half: harvest fan-out -> synthesize -> guard.
 * Promise.all for the harvests: they share nothing, the unit's watchdog bounds them, and
 * OUTER_IN_FLIGHT keeps the total across all in-flight units under the runtime ceiling.
 */
async function harvestAndSynthesize(q, targets, searched) {
  const bundles = (await Promise.all(targets.map((t) => harvestStage(q, t.url)))).filter(Boolean);
  const spansBySource = {};
  for (const b of bundles) {
    if (typeof b?.url === 'string') spansBySource[b.url] = Array.isArray(b.spans) ? b.spans : [];
  }
  const synth = await synthesizeStage(q, bundles);
  const kept = [];
  for (const f of (synth?.findings ?? [])) {
    const g = excerptGuard(f, spansBySource, searched);
    if (g.ok) { kept.push(f); continue; }
    // Recorded, never silently dropped: a claim that failed the verbatim check is a signal about
    // the run's evidence quality, and #96's lesson is that discarded work must still be handed over.
    researchIntegrity.push({ subQuestion: q, claim: f?.claim ?? '(no claim)', reason: g.reason });
  }
  return { findings: kept, gaps: synth?.gaps ?? [], harvested: Object.keys(spansBySource) };
}

/** One sub-question, one full round. */
async function researchRound(q, exclude, cap) {
  const s = await searchAndSelect(q, exclude, cap);
  const h = await harvestAndSynthesize(q, s.targets, s.searched);
  return { ...h, searched: s.searched };
}

const units = subQuestions.map((q) => ({
  validate: (v) => (v && Array.isArray(v.findings) && v.findings.length > 0)
    ? { ok: true } : { ok: false, reason: 'need a non-empty { findings: [{subQuestion, claim, source, excerpt}] } — every excerpt must be a verbatim span of its source' },
  work: () => researchRound(q, [], HARVEST_PER_LEAF),
}));
// 1200s: a unit now holds THREE sequential agent stages (search -> harvest fan-out -> synthesize),
// where it previously held one. The watchdog is NON-PREEMPTIVE — a timed-out unit still runs to
// completion and is still paid for; only its result is discarded — so a budget below the real floor
// buys nothing and, with maxRetries:1, spawns a retry alongside the still-running original.
//
// maxInFlight now uses OUTER_IN_FLIGHT, not MAX_CONCURRENT: each unit is itself a fan-out, so the
// two layers multiply. See the OUTER_IN_FLIGHT comment above for why the excess is a cascade rather
// than a queue you can ignore.
const review = await parallelFanout(units, { perUnitTimeoutMs: 1_200_000, maxInFlight: Math.min(subQuestions.length, OUTER_IN_FLIGHT), modelTier: LEAF_MODEL.includes('haiku') ? 'haiku' : 'sonnet' });

// ── Round 2 — bounded adaptive search ───────────────────────────────────────
// Sequential by design. The budget is a shared counter, so deciding all nine units concurrently
// would let them all read `roundsRemaining > 0` before any decrements it and overspend by 3x. The
// cost is latency on at most ROUNDS_BUDGET units, which is the cheaper of the two failures.
let roundsRemaining = ROUNDS_BUDGET;
const round2Candidates = review.confirmed
  .filter((r) => Array.isArray(r?.gaps) && r.gaps.length > 0)
  .sort((a, b) => b.gaps.length - a.gaps.length);
for (const r1 of round2Candidates) {
  // subQuestion is read off r1.findings[0] because parallelFanout's `confirmed` is a COMPACT
  // array — abandoned units are absent, so the index does not line up with subQuestions. This
  // mirrors the same guard already applied at the section-writer fan-out.
  const q = r1.findings[0]?.subQuestion;
  const needsRound2 = roundsRemaining > 0 && r1.gaps.length > 0 && typeof q === 'string';
  if (!needsRound2) {
    // Budget exhausted: gaps recorded in the integrity channel so the dossier reports what was
    // known-missing rather than presenting round-1 evidence as complete.
    researchIntegrity.push({ subQuestion: q ?? '(unknown)', claim: r1.gaps.join('; '),
      reason: 'gap not researched — run-wide round-2 budget exhausted' });
    continue;
  }
  roundsRemaining -= 1;
  const gapQ = `${q}\nFOCUS ON THESE GAPS: ${r1.gaps.join('; ')}`;
  // Search FIRST, on its own. One agent buys the information needed to decide whether the
  // remaining three are worth spawning.
  const s2 = await searchAndSelect(gapQ, r1.harvested, ROUND2_HARVEST);
  if (roundsConverged(r1.searched, s2.searched)) {
    // >80% repeats means the topic's reachable sources are exhausted. Stopping HERE — before the
    // harvest fan-out and the synthesizer — is the whole value of the check: it saves ~3 agents.
    // Run after the round instead, it could only pick which string to log.
    researchIntegrity.push({ subQuestion: q, claim: r1.gaps.join('; '),
      reason: 'gap not closed — round 2 search returned the same sources (converged)' });
    continue;
  }
  const h2 = await harvestAndSynthesize(gapQ, s2.targets, s2.searched);
  r1.findings.push(...h2.findings);
}
const allFindings = review.confirmed.flatMap((r) => r.findings ?? []);
// Captured here because `review` is shadowed by no later binding but the health calls below read
// only the tier — keeping the read at the source makes the pin's provenance obvious.
const researchModelTier = review.modelTier;

// ── Coverage gate (#96) — the primary fix ───────────────────────────────────
// `review.degraded` has been computed here since the L1 work and never read. The #96 run set it
// correctly to true and the pipeline synthesized anyway, burning ~1.1M tokens to return an empty
// report. Worse, parallelFanout defaults quorum to ceil(units.length / 2) and this consumer never
// passes one — so a run can lose HALF the brief and still report degraded: false.
//
// The gate is authoritative here, not `review.degraded`: it measures the brief actually answered
// (sub-questions with findings) rather than units that merely returned.
const coverage = assessCoverage(subQuestions, allFindings);
if (!coverage.ok) {
  // Stop BEFORE verify and synthesis spend. The raw findings are returned rather than discarded —
  // #96's own complaint was that recoverable work was thrown away, so a stopped run must still
  // hand over everything it bought.
  //
  // Health is computed from signals already in scope, then RETURNED — never used to discard the
  // run's artifacts (#96). Main context surfaces a non-ok verdict; the dossier is handed over either
  // way. `verify: null` because this gate fires before `verified` exists.
  const health = checkRunHealth({
    unitCount: subQuestions.length,
    modelTier: researchModelTier,
    verify: null,
  });
  return {
    health,
    dossierEntry: null,
    findingsDoc: null,
    findings: [],
    rawFindings: allFindings,
    supersedes: [],
    coverage,
    evidenceState: deriveEvidenceState({ findings: [], rawFindings: allFindings, verifyDegraded: false, coverage }),
    runDate: now ?? null,
    stoppedAt: 'coverage-gate',
    verify: null,
    integrity: researchIntegrity,
  };
}

phase('Verify');
// 900s, matching the research leaves above. The previous 300s was justified on the grounds that
// chunking caps each call at <=40 rows — but recheck cost is driven by RE-READING each cited source,
// not by row count, so row-count reasoning does not bound it. Measured Tier-2 cluster durations:
// 114/136/146/196/235/244/299/391/409s. A 300s budget cut off the top two, and because the deadline
// is non-preemptive the abandoned clusters were still paid for in full.
const verified = await tieredVerify(allFindings, { profile: 'web-research', agent, perTierTimeoutMs: 900_000 });
const verifyDegraded = verified.degraded;
let vetted = verifyDegraded ? allFindings : verified.findings;

// ── Diagnose-then-shift reframe (#118 extension — EXPERIMENTAL) ─────────────
// Fires only for sub-questions with NO supported non-thin finding. Exactly one round. The trigger
// comes from verify — an independent adversarial pass — not from a leaf assessing its own work.
// Independence is the property relied on here, NOT source re-reading: `thinSource` is a Tier-1
// triage judgement and that prompt says `Do NOT re-research` (lib/verify.mjs:135-137).
//
// ACCEPTED RISK (by decision, not oversight): success is not measurable with any instrument this
// repo has. `thinSource` is an LLM judgment, so the trigger and the success metric come from the
// same mechanism, and a shift returning different-but-equally-thin sources is indistinguishable
// from one that failed. The recorded diagnosis below is the partial substitute: the DISTRIBUTION of
// diagnosed conditions across real runs is observable, and tells us whether the stage fires on
// conditions it can help.
const REFRAME_SCHEMA = {
  type: 'object', required: ['diagnosis', 'shift', 'queries'],
  properties: {
    diagnosis: { type: 'string' },
    shift: { enum: ['vocabulary', 'abstraction', 'entity-anchored', 'evidence-type', 'inversion', 'discipline'] },
    queries: { type: 'array', items: { type: 'string' } },
  },
};

// Skipped entirely when verify degraded. A degraded verify falls back to the RAW findings, which
// carry no `support` or `thinSource` stamp at all, and reframing on the ABSENCE of a signal is a
// different thing from reframing on one: verify never judged these sources, so we do not know that
// they are thin. The trigger requires a verify that actually ran.
//
// BELT-AND-BRACES, not the only line of defence. `thinSubQuestions` already refuses to classify an
// unjudged thread as thin — it filters to findings carrying a real `support` stamp and returns
// false when none survive — so unstamped findings could not reach the reframe even without this
// guard. Skipping the stage outright when verify degraded makes that intent explicit at the call
// site rather than leaving it implicit in a helper's filtering. It saves no meaningful work —
// `thinSubQuestions` is a synchronous filter over an in-memory array, not an agent call — so the
// value here is clarity, not spend.
const thinQs = verifyDegraded ? [] : thinSubQuestions(subQuestions, vetted);
let reframed = [];
if (thinQs.length) {
  phase('Reframe');
  const moveTable = REFRAME_MOVES.map((m) => `- ${m.key}: WHEN ${m.diagnosis} HOW ${m.instruction}`).join('\n');

  const reframeUnits = thinQs.map((q) => {
    const thinFindings = vetted.filter((f) => f.subQuestion === q);
    return {
      // `diagnosis` is checked, not just named in the reason string. The schema requires it, but the
      // recorded diagnosis is the ONE mitigation the accepted-measurability-risk note above names as
      // this stage's own — a plan that arrives without one reaches the merge as `undefined` and the
      // mitigation silently evaporates. A rejection reason must not claim more than its predicate.
      // The enum is deliberately NOT re-checked here: `mergeReframed` already normalizes `shift`
      // against the closed set it owns, so duplicating that check would give it two homes.
      validate: (v) => (v?.diagnosis && v?.shift && Array.isArray(v?.queries) && v.queries.length > 0 && v.queries.length <= 3)
        ? { ok: true }
        : { ok: false, reason: 'need a diagnosis, one shift from the enum, and 1-3 reformulated queries' },
      // `work` stamps the sub-question onto its OWN result. parallelFanout's `confirmed` is a
      // COMPACT array — abandoned units are absent, not null — so a positional thinQs[i] lookup
      // would silently mislabel every plan after the first abandon. Reconstruct by KEY, never by
      // position; this is the same rule the section fan-out already follows.
      //
      // The stamp comes LAST, after the spread — the code-owned key must win. REFRAME_SCHEMA does
      // not set `additionalProperties: false` and the prompt prints the sub-question verbatim, so
      // an agent that echoes back a paraphrased `subQuestion` would clobber a stamp placed first.
      // Downstream matches this key EXACTLY; a paraphrase matches nothing and the re-researched
      // findings are dropped in silence. Same invariant as `mergeReframed`: an agent never types a
      // flag the code owns.
      work: async (repair) => ({ ...await agent(
        `Research on this sub-question produced only THIN evidence: no well-supported, ` +
        `non-low-authority source. Your job is to work out WHY, then pick the ONE move that ` +
        `matches — not to reformulate reflexively.\n\n` +
        `STEP 1 — DIAGNOSE. State in one sentence why the evidence is thin.\n` +
        `STEP 2 — SELECT the single matching move:\n${moveTable}\n\n` +
        `STEP 3 — Write 1-3 reformulated queries applying ONLY that move.\n\n` +
        // The 240s budget below assumes this stage does no web work. Nothing in the steps above
        // forbids it, and "mine these for terminology" invites it — so say it, the same way the
        // section-writer prompt spells out its own no-new-research constraint.
        `Do NOT search the web and do NOT fetch any page. You are PLANNING queries, not running ` +
        `them: reason over the thin sources already provided below and return queries for someone ` +
        `else to run.\n` +
        // The anchor. The failure mode of reformulation is drifting to an adjacent, easier
        // question — which the mechanical checks in Task 19 enforce, but state it here too.
        `Every query must still serve the ORIGINAL sub-question verbatim below. A query that ` +
        `answers something adjacent and easier is DRIFT and will be rejected downstream.\n` +
        `ORIGINAL SUB-QUESTION: ${q}\n` +
        `THIN SOURCES FOUND (mine these for terminology — they are weak, not useless): ` +
        `${JSON.stringify(thinFindings.map((f) => ({ source: f.source, claim: f.claim })))}\n` +
        (repair ? `PREVIOUS ATTEMPT REJECTED: ${repair}. Fix it.\n` : ''),
        { label: `reframe:${q.slice(0, 40)}`, phase: 'Reframe', schema: REFRAME_SCHEMA, model: 'claude-sonnet-4-6' }), subQuestion: q }),
    };
  });

  // 240s: this stage plans queries, it does not run them. The re-research below carries the
  // web-facing budget.
  //
  // quorum: 0 — this stage is OPTIONAL, so no number of successes is *required*. Note this does
  // NOT suppress the returned `degraded` flag: dispatch.mjs:61-62 special-cases quorum 0 so that
  // any abandon still sets degraded, and dispatch.test.mjs locks that in ("zero-quorum does not
  // mask abandons"). We simply never READ `.degraded` from either reframe fan-out — the run's
  // trust signals come from `coverage` and `evidenceState`, and a failed reframe must leave the
  // run intact with its thin findings. Do not later wire these `.degraded` values into a caller
  // signal expecting quorum 0 to mean "abandons are fine".
  const reframePlans = await parallelFanout(reframeUnits, { perUnitTimeoutMs: 240_000, maxInFlight: Math.min(thinQs.length, MAX_CONCURRENT), modelTier: 'sonnet', quorum: 0 });
  const plans = reframePlans.confirmed;   // each already carries its own subQuestion

  // ── Narrow re-research: one leaf per plan, running ONLY that plan's queries ──
  const researchUnits = plans.map((plan) => ({
    validate: (v) => (v && Array.isArray(v.findings)) ? { ok: true } : { ok: false, reason: 'need { findings: [...] } (an empty array is a valid answer)' },
    // Same compact-array rule: carry the plan on the result rather than re-deriving it by position.
    work: async (repair) => ({ plan, findings: (await agent(
      // The anti-memory contract, carried over from the primary research leaf verbatim in intent.
      // This stage exists to obtain BETTER SOURCES; a memory-answered finding arrives with a
      // plausible-looking URL, survives the re-verify, and can be stamped `supported` — defeating
      // the whole stage while looking like success. The search budget is honoured here too, in the
      // same conditional form as the primary leaf: this is the other web-facing fan-out, so a
      // caller's cap that binds one and not the other is not a cap.
      `You are a research analyst running a NARROW follow-up. Investigate by SEARCHING THE WEB — ` +
      `do NOT answer from memory. Run ONLY these queries and report ` +
      `what you find:\n${plan.queries.map((s) => `- ${s}`).join('\n')}\n\n` +
      (maxSearchesPerLeaf != null ? `Search budget: perform at most ${maxSearchesPerLeaf} WebSearch calls, then synthesize from what you have found.\n` : '') +
      `Set "subQuestion" on EVERY finding to exactly: ${plan.subQuestion}\n` +
      `Set "source" to the URL the claim came from. Prefer primary and authoritative sources. ` +
      `If these queries surface nothing better than what we already had, return an EMPTY findings ` +
      `array — that is a valid and useful answer, not a failure.\n` +
      (repair ? `PREVIOUS ATTEMPT REJECTED: ${repair}. Fix it.\n` : ''),
      { label: `reresearch:${plan.subQuestion.slice(0, 40)}`, phase: 'Reframe', schema: FINDINGS, model: LEAF_MODEL }))?.findings ?? [] }),
  }));

  const reResearch = await parallelFanout(researchUnits, { perUnitTimeoutMs: 900_000, maxInFlight: Math.min(researchUnits.length, MAX_CONCURRENT), modelTier: LEAF_MODEL.includes('haiku') ? 'haiku' : 'sonnet', quorum: 0 });
  reframed = reResearch.confirmed.flatMap((r) => r.findings.map((f) => ({ ...f, _plan: r.plan })));

  // Re-verified BEFORE merging, and — critically — against the ORIGINAL sub-question, never the
  // reformulated query. A finding that answers the reformulation but not the original one IS
  // drift; triage labels it accordingly rather than admitting it. This is the mechanical form of
  // the anchor. ReformIR suppresses drift with ranker FEEDBACK anchored to the original query;
  // telling the reframe agent to stay on topic is the weaker, prompt-only form.
  //
  // Only the VERIFY call is gated on `reframed.length` — an empty re-research has nothing to
  // verify, so the pass would be pure waste.
  let candidates = [];
  if (reframed.length) {
    const reVerified = await tieredVerify(
      reframed.map(({ _plan, ...f }) => ({ ...f, subQuestion: _plan.subQuestion })),
      { profile: 'web-research', agent, perTierTimeoutMs: 900_000 },
    );
    // A degraded re-verify yields NO candidates. The merge bar is `supported && !thinSource`, and
    // unverified findings have neither label — admitting them would let the reframe bypass exactly
    // the scrutiny it was triggered by.
    candidates = reVerified.degraded ? [] : reVerified.findings;
  }

  // The MERGE is gated on `plans`, NOT on `reframed.length` — and the `plans.length` guard is a
  // pure optimization: with `plans` empty the loop body never runs and the reassignment below
  // would be an identity copy.
  //
  // `plans` and `reframed` come from two independent fan-outs: a plan can exist while its
  // re-research validly returns zero findings — Task 18's own prompt invites exactly that ("return
  // an EMPTY findings array — that is a valid and useful answer, not a failure"), and with three of
  // six moves unvalidated it is likely the COMMON outcome. Gating this loop on `reframed.length`
  // would skip `mergeReframed` in precisely that case, losing the `improved: false` stamp — which
  // is the recorded-diagnosis signal that Slice 4's accepted measurability risk names as its own
  // partial mitigation. A stage whose failures go unrecorded cannot be improved.
  if (plans.length) {
    const merged = [];
    for (const plan of plans) {
      const thinForQ = vetted.filter((f) => f.subQuestion === plan.subQuestion);
      merged.push(...mergeReframed(
        thinForQ,
        candidates.filter((f) => f.subQuestion === plan.subQuestion),
        { subQuestion: plan.subQuestion, diagnosis: plan.diagnosis, shift: plan.shift },
      ));
    }
    // Replace only the reframed sub-questions' findings; everything else is untouched.
    const touched = new Set(plans.map((p) => p.subQuestion));
    vetted = [...vetted.filter((f) => !touched.has(f.subQuestion)), ...merged];
  }
}

